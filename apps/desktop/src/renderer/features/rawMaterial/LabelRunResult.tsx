import React, { useState } from "react";
import type { RawMaterialQrBatchRow, RawMaterialQrRow } from "../../types/desktopApi";
import { copy } from "../../config/copy";
import { useNotifications } from "../../state/NotificationsContext";
import { QrPreview } from "../../utils/qrLabels";
import { packetContentsLabel } from "./rawMaterial";

// What one registered run came to: its facts, the identities it took, and the first few
// stickers drawn so the operator can see the codes are real.
//
// One press of Print may register a run per material, so this is rendered once per run rather
// than once per press.

/** How many stickers are drawn under a run; the rest are in the preview window. */
const PREVIEW_LIMIT = 12;

interface LabelRunResultProps {
  batch: RawMaterialQrBatchRow;
  qrCodes: RawMaterialQrRow[];
  /** The stock unit the material is counted in, for "one packet holds". */
  unitCode: string;
  identityAt: (partyCode: string, itemCode: string, sequence: number) => string;
  onPreview: () => void;
  onPrintAgain: () => void;
}

export const LabelRunResult: React.FC<LabelRunResultProps> = ({ batch, qrCodes, unitCode, identityAt, onPreview, onPrintAgain }) => {
  const { push } = useNotifications();
  const [copied, setCopied] = useState(false);

  const copyIdentities = async () => {
    try {
      await navigator.clipboard.writeText(qrCodes.map((code) => code.id).join("\n"));
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      push("error", copy.toast.copyFailed, "Could not copy to the clipboard");
    }
  };

  return (
    <div className="qr-input-card qr-result-card">
      <div className="card-header">
        <h2 className="card-title">
          <span className="badge badge-ok">Done</span> {batch.quantity.toLocaleString()} labels · {batch.itemDisplayName}
        </h2>
        <div className="qr-result-actions">
          <button type="button" className="btn btn-secondary" onClick={() => void copyIdentities()}>
            {copied ? "Copied" : "Copy list"}
          </button>
          <button type="button" className="btn btn-secondary" onClick={onPreview}>
            {copy.labelPrint.preview}
          </button>
          <button type="button" className="btn btn-primary" onClick={onPrintAgain}>
            {copy.labelPrint.printAgain}
          </button>
        </div>
      </div>

      <div className="qr-result-facts">
        <div>
          <span className="section-label">{copy.columns.supplier}</span>
          <strong>{batch.partyName}</strong>
        </div>
        <div>
          <span className="section-label">{copy.columns.quantity}</span>
          <strong>{batch.quantity.toLocaleString()}</strong>
        </div>
        {batch.packingQuantity != null ? (
          <div>
            <span className="section-label">One packet holds</span>
            <strong>{packetContentsLabel(batch.packingQuantity, unitCode)}</strong>
          </div>
        ) : null}
        <div>
          <span className="section-label">Generated by</span>
          <strong>{batch.createdBy ?? "—"}</strong>
        </div>
        {batch.requestedBy ? (
          <div>
            <span className="section-label">Requested by</span>
            <strong>{batch.requestedBy}</strong>
          </div>
        ) : null}
      </div>

      <div className="qr-pending qr-range-block">
        <p className="summary-block-title">Generated</p>
        <div className="qr-range">
          <code className="qr-identity">{identityAt(batch.partyCode, batch.itemCode, batch.startSequence)}</code>
          <span className="qr-range-sep">→</span>
          <code className="qr-identity">{identityAt(batch.partyCode, batch.itemCode, batch.endSequence)}</code>
        </div>
      </div>

      <div className="qr-preview-grid">
        {qrCodes.slice(0, PREVIEW_LIMIT).map((code) => (
          <div key={code.id} className="qr-preview-cell">
            <QrPreview value={code.id} />
          </div>
        ))}
      </div>
      {qrCodes.length > PREVIEW_LIMIT ? (
        <p className="field-help">
          Showing the first {PREVIEW_LIMIT} of {qrCodes.length.toLocaleString()}. Use {copy.labelPrint.preview} to see the whole run.
        </p>
      ) : null}
    </div>
  );
};
